#ifndef __SORT_API__        /* __SORT_API__  */
#define __SORT_API__        /* __SORT_API__  */

#include <stddef.h>         /* size_t        */

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(n)
*           * Worst: O(n^2)
*           * Average: O(n^2)
*/      void BubbleSort(int *arr, size_t size);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(n)
*           * Worst: O(n^2)
*           * Average: O(n^2)
*/      void InsertionSort(int *arr, size_t size);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(n^2)
*           * Worst: O(n^2)
*           * Average: O(n^2)
*/      void SelectionSort(int *arr, size_t size);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(n + k)
*           * Worst: O(n + k)
*           * Average: O(n + k)
*/      int CountingSort(int *arr, size_t size);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(d(n + k))
*           * Worst: O(d(n + k))
*           * Average: O(d(n + k))
*/      int RadixSort(int *arr, size_t size);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(log n)
*           * Worst: O(log n)
*           * Average: O(log n)
*/      int BinarySearchIterative(int *arr, size_t size, int num);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(log n)
*           * Worst: O(log n)
*           * Average: O(log n)
*/      int* BinarySearchRecursive(int *arr, size_t size, int num);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(n log n)
*           * Worst: O(n log n)
*           * Average: O(n log n)
*/      int MergeSort(int *arr, size_t size);
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(n log n)
*           * Worst: O(n^2)
*           * Average: O(n log n)
*/      void QuickSort(void *arr, size_t count, size_t element_size,
                       int (*cmp_func)(const void *, const void *));
/*
******************************************************************************/

/******************************************************************************
*
*       Time Complexity:
*           * Best: O(n log n)
*           * Worst: O(n log n)
*           * Average: O(n log n)
*/      void HeapSort(int *arr, size_t size);
/*
******************************************************************************/

#endif                      /* __SORT_API__  */